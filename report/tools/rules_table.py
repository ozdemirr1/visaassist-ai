"""Write appendices/a-rules.tex from data/requirements/, so the report and the data agree.

    cd backend && uv run python ../report/tools/rules_table.py
"""

import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPORT.parent / "backend"))

from app.requirements.loader import load_requirement_data  # noqa: E402

PROFILES = {"employed": "E", "student": "S"}


def tex(text: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"),
                 ("#", r"\#"), ("$", r"\$")):
        text = text.replace(a, b)
    return text


def rid(text: str) -> str:
    """An identifier that may break after its hyphens in a narrow column."""
    return r"\reqid{" + tex(text).replace("-", r"-\allowbreak{}") + "}"


def layer_name(layer) -> str:
    return "EU" if layer.layer == "eu" else layer.destination


def main() -> None:
    data = load_requirement_data()
    titles = {d.id: d.title.en for d in data.catalog.document_types}
    items, rules = [], []
    for layer in data.layers:
        for r in layer.requirements:
            items.append(
                rf"{rid(r.id)} & {layer_name(layer)} & "
                rf"{','.join(PROFILES[p] for p in r.profiles)} & {tex(titles[r.document])} & "
                rf"{tex(r.source.section)} \\"
            )
        for r in layer.rules:
            check = r.check.kind if hasattr(r.check, "kind") else r.check["kind"]
            rules.append(
                rf"{rid(r.id)} & {layer_name(layer)} & "
                rf"{','.join(PROFILES[p] for p in r.profiles)} & \texttt{{{tex(check)}}} & "
                rf"{r.severity} & {tex(r.source.section)} \\"
            )
    head = r"""\chapter{Requirements and Rules of the Pilot}\label{app:rules}
% Generated by report/tools/rules_table.py from data/requirements/; do not edit by hand.
The tables list every checklist item and every rule of the requirement files (layer: the EU
baseline or a national layer; profiles: E employed, S student). The cited passages are in the
files themselves.

{\footnotesize\setlength{\tabcolsep}{4pt}
\begin{longtable}{@{}>{\raggedright\arraybackslash}p{4.3cm}ll>{\raggedright\arraybackslash}p{4.0cm}>{\raggedright\arraybackslash}p{4.4cm}@{}}
  \caption{Checklist items.}\label{tab:items}\\
  \toprule
  ID & Layer & Prof. & Document & Source section \\
  \midrule
  \endfirsthead
  \toprule
  ID & Layer & Prof. & Document & Source section \\
  \midrule
  \endhead
  \bottomrule
  \endfoot
"""
    middle = r"""\end{longtable}

\begin{longtable}{@{}>{\raggedright\arraybackslash}p{4.6cm}ll>{\raggedright\arraybackslash}p{3.8cm}l>{\raggedright\arraybackslash}p{2.8cm}@{}}
  \caption{Rules.}\label{tab:rules}\\
  \toprule
  ID & Layer & Prof. & Check & Severity & Source section \\
  \midrule
  \endfirsthead
  \toprule
  ID & Layer & Prof. & Check & Severity & Source section \\
  \midrule
  \endhead
  \bottomrule
  \endfoot
"""
    out = head + "\n".join(items) + "\n" + middle + "\n".join(rules) + "\n\\end{longtable}\n}\n"
    (REPORT / "appendices" / "a-rules.tex").write_text(out, encoding="utf-8")
    print(f"{len(items)} checklist items, {len(rules)} rules")


if __name__ == "__main__":
    main()
